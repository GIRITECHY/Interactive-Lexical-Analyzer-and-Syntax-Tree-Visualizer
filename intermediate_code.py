"""
intermediate_code.py - Three-Address Code (TAC) Generator for LexiTree

Traverses the Abstract Syntax Tree (AST) generated by the parser and synthesizes
an intermediate representation (IR) in Three-Address Code (TAC) form.

Rules:
- Respects operator precedence and parentheses hierarchy as encoded in the AST.
- Produces deterministic temporary variable names (t1, t2, t3, ...).
- Resets temporary variable numbering at the start of each generation pass.
- Supports variable assignments, binary operations (+, -, *, /), unary operators (+, -),
  and multiple statements.
- Preserves raw numeric literals to avoid unintended floating-point rounding.
"""

from typing import List, Union
from ast_nodes import (
    ASTNode,
    Program,
    Assignment,
    BinaryOp,
    UnaryOp,
    Number,
    Identifier
)


class TACGenerator:
    """
    Synthesizes Three-Address Code instructions from a validated AST.
    """

    def __init__(self):
        self.temp_counter = 1
        self.instructions: List[str] = []

    def _new_temp(self) -> str:
        """Allocate a new temporary variable identifier (e.g., 't1', 't2')."""
        temp_name = f"t{self.temp_counter}"
        self.temp_counter += 1
        return temp_name

    def generate(self, node: ASTNode) -> List[str]:
        """
        Main entry point: Generates a list of Three-Address Code instruction strings from the AST.
        Resets temporary numbering for each independent compilation pass.
        """
        self.temp_counter = 1
        self.instructions = []

        if node is None:
            return []

        if isinstance(node, Program):
            for stmt in node.statements:
                self._generate_statement(stmt)
        elif isinstance(node, Assignment):
            self._generate_statement(node)
        else:
            self._generate_expr(node)

        return list(self.instructions)

    def _generate_statement(self, stmt: Assignment):
        """Generates TAC for an Assignment AST node."""
        if not isinstance(stmt, Assignment):
            raise ValueError(f"Expected Assignment statement node, got {type(stmt).__name__}")

        target_name = stmt.identifier.name
        expr_result = self._generate_expr(stmt.value)
        self.instructions.append(f"{target_name} = {expr_result}")

    def _generate_expr(self, node: ASTNode) -> str:
        """
        Recursively translates an expression subtree into TAC instructions.
        Returns the variable name, literal value, or temporary representing the evaluated sub-expression.
        """
        if isinstance(node, Number):
            # Preserve raw textual representation where available to prevent float formatting anomalies
            if node.raw is not None and str(node.raw).strip() != "":
                return str(node.raw)
            return str(node.value)

        elif isinstance(node, Identifier):
            return node.name

        elif isinstance(node, BinaryOp):
            # Left operand evaluated first, then right operand
            left_result = self._generate_expr(node.left)
            right_result = self._generate_expr(node.right)
            temp = self._new_temp()
            self.instructions.append(f"{temp} = {left_result} {node.operator} {right_result}")
            return temp

        elif isinstance(node, UnaryOp):
            if node.operator == "+":
                # Unary plus does not alter magnitude; avoid redundant temporary assignment
                return self._generate_expr(node.operand)
            elif node.operator == "-":
                operand_result = self._generate_expr(node.operand)
                temp = self._new_temp()
                self.instructions.append(f"{temp} = -{operand_result}")
                return temp
            else:
                raise ValueError(f"Unsupported unary operator: {node.operator}")

        else:
            raise ValueError(f"Unknown or unsupported AST node encountered in TAC generation: {type(node).__name__}")

